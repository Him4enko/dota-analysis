def _pct(x: float | None, d: int = 1) -> str:
    if x is None or (isinstance(x, float) and x != x):
        return "—"
    return f"{x * 100:.{d}f}%"


def _num(x, d: int = 2) -> str:
    if x is None or (isinstance(x, float) and x != x):
        return "—"
    return f"{x:.{d}f}"


def _ci(ci, d: int = 1) -> str:
    if not ci or ci[0] != ci[0]:
        return "—"
    return f"{ci[0] * 100:.{d}f}–{ci[1] * 100:.{d}f}%"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def _fig(name: str, caption: str) -> str:
    return f"![{caption}](figures/{name})\n\n*{caption}*\n"


def _sp(n) -> str:
    return f"{int(n):,}".replace(",", " ")


def _trend_ru(name: str) -> str:
    return {
        "increasing": "рост",
        "decreasing": "снижение",
        "no significant trend": "значимого тренда нет",
    }.get(name, name)


